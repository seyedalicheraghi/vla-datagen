"""MachineSpec → URDF text + JSON metadata sidecar (pure Python)."""

from __future__ import annotations

import json
import os
from xml.sax.saxutils import escape

from . import kinematics as K
from .spec import Box, Cylinder, Link, MachineSpec, Shape, Sphere

# Revolute/prismatic limits are written this far OUTSIDE the spec limits.  Isaac Lab
# rejects default joint positions outside the PhysX limits (compared in float32,
# revolute limits round-tripped through degrees), and many joints start exactly on
# a limit.  The environment clamps every joint to the exact spec limits itself.
LIMIT_PAD = 1e-4

ASSET_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..",
                                          "assets", "heavy_machines"))


# ---------------------------------------------------------------------------
# Inertia
# ---------------------------------------------------------------------------

def _shape_inertia_local(shape: Shape, mass: float) -> K.Mat3:
    g = shape.geom
    if isinstance(g, Box):
        x, y, z = g.size
        return ((mass * (y * y + z * z) / 12, 0.0, 0.0),
                (0.0, mass * (x * x + z * z) / 12, 0.0),
                (0.0, 0.0, mass * (x * x + y * y) / 12))
    if isinstance(g, Cylinder):
        r, h = g.radius, g.length
        ixx = mass * (3 * r * r + h * h) / 12
        return ((ixx, 0.0, 0.0), (0.0, ixx, 0.0), (0.0, 0.0, mass * r * r / 2))
    if isinstance(g, Sphere):
        i = 0.4 * mass * g.radius ** 2
        return ((i, 0.0, 0.0), (0.0, i, 0.0), (0.0, 0.0, i))
    raise TypeError(g)


def link_inertia(link: Link) -> tuple[float, K.Vec3, K.Mat3]:
    """(mass, centre of mass, inertia about the COM) in the link frame.

    Mass is spread over the link's shapes in proportion to their volume.
    """
    shapes = link.shapes
    vols = [K.shape_volume(s) for s in shapes]
    vtot = sum(vols)
    if not shapes or vtot <= 0:
        i = max(link.mass, 1e-3) * 1e-2
        return link.mass, (0.0, 0.0, 0.0), ((i, 0, 0), (0, i, 0), (0, 0, i))
    masses = [link.mass * v / vtot for v in vols]
    com = (0.0, 0.0, 0.0)
    for s, m in zip(shapes, masses):
        com = K.vadd(com, K.vscale(s.xyz, m))
    com = K.vscale(com, 1.0 / link.mass)

    total = [[0.0] * 3 for _ in range(3)]
    for s, m in zip(shapes, masses):
        R = K.rpy_to_mat(s.rpy)
        I_rot = K.mat_mul(K.mat_mul(R, _shape_inertia_local(s, m)), K.transpose(R))
        d = K.vsub(s.xyz, com)
        dd = d[0] ** 2 + d[1] ** 2 + d[2] ** 2
        for i in range(3):
            for j in range(3):
                total[i][j] += I_rot[i][j] + m * ((dd if i == j else 0.0) - d[i] * d[j])
    eps = 1e-4 * link.mass                       # keep PhysX happy for thin links
    for i in range(3):
        total[i][i] += eps
    return link.mass, com, tuple(tuple(r) for r in total)  # type: ignore[return-value]


# ---------------------------------------------------------------------------
# URDF
# ---------------------------------------------------------------------------

def _f(x: float) -> str:
    s = f"{x:.6f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def _v(v) -> str:
    return " ".join(_f(x) for x in v)


def _geometry_xml(shape: Shape) -> str:
    g = shape.geom
    if isinstance(g, Box):
        return f'<box size="{_v(g.size)}"/>'
    if isinstance(g, Cylinder):
        return f'<cylinder radius="{_f(g.radius)}" length="{_f(g.length)}"/>'
    if isinstance(g, Sphere):
        return f'<sphere radius="{_f(g.radius)}"/>'
    raise TypeError(g)


def build_urdf(spec: MachineSpec) -> str:
    out: list[str] = ['<?xml version="1.0"?>',
                      f"<!-- Generated by scripts/heavy_machines/generate.py from "
                      f"machines/{spec.name}.py — do not edit by hand. -->",
                      f'<robot name="{escape(spec.name)}">']
    used = {s.material for lk in spec.links for s in lk.shapes if s.visual}
    for name in sorted(used):
        rgba = spec.materials[name]
        out.append(f'  <material name="{name}"><color rgba="{_v(rgba)}"/></material>')

    for lk in spec.links:
        mass, com, I = link_inertia(lk)
        out.append(f'  <link name="{lk.name}">')
        for s in lk.shapes:
            origin = f'<origin xyz="{_v(s.xyz)}" rpy="{_v(s.rpy)}"/>'
            if s.visual:
                out.append(f"    <visual>{origin}<geometry>{_geometry_xml(s)}</geometry>"
                           f'<material name="{s.material}"/></visual>')
            if s.collision:
                out.append(f"    <collision>{origin}<geometry>{_geometry_xml(s)}</geometry></collision>")
        out.append(f'    <inertial><origin xyz="{_v(com)}" rpy="0 0 0"/><mass value="{_f(mass)}"/>'
                   f'<inertia ixx="{_f(I[0][0])}" ixy="{_f(I[0][1])}" ixz="{_f(I[0][2])}" '
                   f'iyy="{_f(I[1][1])}" iyz="{_f(I[1][2])}" izz="{_f(I[2][2])}"/></inertial>')
        out.append("  </link>")

    for jt in spec.joints:
        out.append(f'  <joint name="{jt.name}" type="{jt.type}">')
        out.append(f'    <parent link="{jt.parent}"/><child link="{jt.child}"/>')
        out.append(f'    <origin xyz="{_v(jt.xyz)}" rpy="{_v(jt.rpy)}"/>')
        if jt.type != "fixed":
            out.append(f'    <axis xyz="{_v(K.vunit(jt.axis))}"/>')
        if jt.type in ("revolute", "prismatic"):
            out.append(f'    <limit lower="{jt.lower - LIMIT_PAD:.9g}" upper="{jt.upper + LIMIT_PAD:.9g}" '
                       f'effort="{_f(jt.effort)}" velocity="{_f(jt.velocity)}"/>')
        elif jt.type == "continuous":
            out.append(f'    <limit effort="{_f(jt.effort)}" velocity="{_f(jt.velocity)}"/>')
        out.append("  </joint>")
    out.append("</robot>")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# JSON sidecar (action / state layout for downstream tools)
# ---------------------------------------------------------------------------

def metadata(spec: MachineSpec) -> dict:
    lo, hi = K.bounding_box(spec)
    tools = []
    for i, t in enumerate(spec.tools):
        jt = spec.joint(t.joint)
        unit = "m" if jt.type == "prismatic" else "rad"
        tools.append({
            "action_index": 2 + i, "label": t.label, "joint": t.joint, "type": jt.type,
            "unit": unit, "rate_at_full_command": jt.velocity,
            "lower": None if jt.type == "continuous" else jt.lower,
            "upper": None if jt.type == "continuous" else jt.upper,
            "init": jt.init, "positive": t.positive, "negative": t.negative,
        })
    d = spec.drive
    drive = {"type": d.type, "max_speed_mps": d.max_speed, "max_reverse_speed_mps": d.reverse_speed}
    if d.type == "skid":
        drive.update(max_yaw_rate_radps=d.max_yaw_rate, track_width_m=d.track_width)
    elif d.type == "ackermann":
        drive.update(wheelbase_m=d.wheelbase, max_steer_rad=d.max_steer, steer_rate_radps=d.steer_rate,
                     fixed_axle_x_m=d.fixed_axle_x, steer_axle=d.steer_axle)
    else:
        aj = spec.joint(d.articulation_joint)
        drive.update(articulation_joint=d.articulation_joint, front_length_m=d.front_length,
                     rear_length_m=d.rear_length, articulation_rate_radps=d.articulation_rate,
                     max_articulation_rad=min(abs(aj.lower), abs(aj.upper)))
    return {
        "name": spec.name, "abbrev": spec.abbrev, "display_name": spec.display_name,
        "category": spec.category, "reference": spec.reference, "description": spec.description,
        "urdf": f"{spec.name}.urdf", "root_link": spec.root,
        "root_height_m": round(K.root_height(spec), 4),
        "operating_mass_kg": spec.operating_mass, "model_mass_kg": round(spec.total_mass, 1),
        "envelope_m": list(spec.envelope),
        "model_bbox_m": [round(hi[i] - lo[i], 3) for i in range(3)],
        "action": {
            "dim": spec.action_dim,
            "range": [-1.0, 1.0],
            "channels": [
                {"action_index": 0, "label": "drive", "positive": "forward", "negative": "reverse"},
                {"action_index": 1, "label": "turn", "positive": "left", "negative": "right"},
            ] + tools,
        },
        "state": {"dim": len(spec.state_labels), "labels": spec.state_labels},
        "drive": drive,
        "joints": [{"name": j.name, "type": j.type, "role": j.role, "parent": j.parent,
                    "child": j.child, "lower": j.lower, "upper": j.upper, "init": j.init,
                    "velocity": j.velocity}
                   for j in spec.joints if j.type != "fixed"],
        "cameras": [{"name": c.name, "link": c.link, "xyz": list(c.xyz), "rpy": list(c.rpy)}
                    for c in spec.cameras],
    }


def write_assets(spec: MachineSpec, root: str = ASSET_ROOT) -> tuple[str, str]:
    """Write <root>/<name>/<name>.urdf and <name>.json; only touches files that changed."""
    d = os.path.join(root, spec.name)
    os.makedirs(d, exist_ok=True)
    urdf_path = os.path.join(d, f"{spec.name}.urdf")
    json_path = os.path.join(d, f"{spec.name}.json")
    for path, text in ((urdf_path, build_urdf(spec)),
                       (json_path, json.dumps(metadata(spec), indent=2) + "\n")):
        old = None
        if os.path.exists(path):
            with open(path) as f:
                old = f.read()
        if old != text:
            with open(path, "w") as f:
                f.write(text)
    return urdf_path, json_path
